#!/usr/bin/env python3
"""Read outputs/mpi_dlt_baseline_detected_2d.json and update docs."""

from __future__ import annotations

import json
import time
from pathlib import Path

LOCAL_REPO = Path(__file__).resolve().parents[1]
JSON_PATH = LOCAL_REPO / "outputs" / "mpi_dlt_baseline_detected_2d.json"
RESULTS_DOC = LOCAL_REPO / "docs" / "results_true_gt_h36m.md"
HANDOFF_DOC = LOCAL_REPO / "docs" / "handoff_qwen3.8max.md"


def main() -> int:
    data = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    mpjpe = float(data["mean_mpjpe_mm"])
    pa_mpjpe = float(data["mean_pa_mpjpe_mm"])
    num_files = len(data["per_file"])

    if num_files < 16:
        raise RuntimeError(f"Only {num_files}/16 files in JSON; not recording yet")

    # Update results doc
    text = RESULTS_DOC.read_text(encoding="utf-8")
    old_block = (
        "| Status | Files ready | DLT MPJPE (mm) | PA-MPJPE (mm) | Notes |\n"
        "|---|---:|---:|---:|---|\n"
        "| Partial | 4 / 16 | **150.50** | **164.22** | Mean over the first two completed files (`s_01_seq_01_02_v14_multiview_m.npz` 138.31 mm, `s_01_seq_01_v14_multiview_m.npz` 162.69 mm); not representative. Full MPI DLT pending remaining files. |\n"
        "| Full | pending | — | — | Pending completion of RTMPose detection for all sequences. |"
    )
    new_block = (
        f"| Status | Files ready | DLT MPJPE (mm) | PA-MPJPE (mm) | Notes |\n"
        "|---|---:|---:|---:|---|\n"
        f"| **Full** | **16 / 16** | **{mpjpe:.3f}** | **{pa_mpjpe:.3f}** | RTMPose detected-2D, confidence-weighted DLT over all MPI-INF-3DHP test sequences. |"
    )
    if old_block not in text:
        raise RuntimeError("Could not find expected MPI DLT baseline table block in results doc")
    text = text.replace(old_block, new_block)

    old_para = (
        "**MPI-INF-3DHP DLT baseline** is in progress. Four of 16 expected detected-2D files have been generated; the mean DLT on the first two files is **150.50 mm** / PA-MPJPE **164.22 mm**, which is not representative. Full MPI DLT results are pending."
    )
    new_para = (
        f"**MPI-INF-3DHP DLT baseline** is complete. All 16 detected-2D files were generated, and the confidence-weighted DLT baseline reports **{mpjpe:.3f} mm** MPJPE / **{pa_mpjpe:.3f} mm** PA-MPJPE."
    )
    text = text.replace(old_para, new_para)

    RESULTS_DOC.write_text(text, encoding="utf-8")
    print(f"Updated {RESULTS_DOC}")

    # Update handoff doc
    if HANDOFF_DOC.exists():
        content = HANDOFF_DOC.read_text(encoding="utf-8")
    else:
        content = "# Handoff for qwen3.8max\n\n"
    timestamp = time.strftime("%Y-%m-%d %H:%M UTC")
    section = f"\n## MPI-INF-3DHP DLT baseline ({timestamp})\n\n"
    section += f"- Status: **complete**\n"
    section += f"- Files: **16/16** detected-2D `.npz` files generated by RTMPose on A800 GPU 7\n"
    section += f"- DLT MPJPE: **{mpjpe:.3f} mm**\n"
    section += f"- DLT PA-MPJPE: **{pa_mpjpe:.3f} mm**\n"
    section += f"- Source JSON (A800): `{JSON_PATH}`\n"
    section += f"- Updated docs: `docs/results_true_gt_h36m.md`\n"
    content += section
    HANDOFF_DOC.write_text(content, encoding="utf-8")
    print(f"Updated {HANDOFF_DOC}")

    print(f"\nMPI-INF-3DHP DLT baseline: {mpjpe:.3f} mm / {pa_mpjpe:.3f} mm PA-MPJPE")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
